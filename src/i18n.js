const DICTS = { zh, en }

export function useI18n() {
  const settings = useSettingsStore()
  const t = (key, params = {}) => {
    const dict = DICTS[settings.locale] || zh
    let s = dict[key]
    if (s === undefined) s = zh[key]  // fallback to zh if en is missing the key
    if (s === undefined) return key   // last-resort: show the key, helps debugging
    for (const k in params) s = s.replaceAll('{' + k + '}', params[k])
    return s
  }
  return { t, locale: computed(() => settings.locale) }
}

// Non-reactive variant for use outside SFCs (utilities, store actions).
export function t(key, params = {}) {
  // Re-import lazily to avoid circular issues at module init.
  const settings = useSettingsStore()
  const dict = DICTS[settings.locale] || zh
  let s = dict[key]
  if (s === undefined) s = zh[key]
  if (s === undefined) return key
  for (const k in params) s = s.replaceAll('{' + k + '}', params[k])
  return s
}
